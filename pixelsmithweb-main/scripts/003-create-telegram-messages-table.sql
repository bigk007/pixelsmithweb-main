-- Conversation memory for the Telegram support bot (optional).
-- Without this table the bot still works, but answers each message on its own.

CREATE TABLE IF NOT EXISTS telegram_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id BIGINT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
  content TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_telegram_messages_chat ON telegram_messages(chat_id, created_at DESC);

-- The bot uses the service_role key, which bypasses RLS. Enabling RLS with no
-- policies keeps the table private from the public anon key.
ALTER TABLE telegram_messages ENABLE ROW LEVEL SECURITY;
