CREATE TABLE IF NOT EXISTS quiz_results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL CHECK (email ~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}$'), -- Basic email format validation
  business_name TEXT, -- Optional
  
  -- Quiz Answers
  challenge TEXT NOT NULL,
  business_type TEXT NOT NULL,
  budget TEXT NOT NULL,
  goal TEXT NOT NULL,
  
  submitted_at TIMESTAMPTZ DEFAULT NOW() NOT NULL, -- Timestamp of submission
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL -- Timestamp of record creation (can be same as submitted_at)
);

-- Add comments to columns for clarity
COMMENT ON COLUMN quiz_results.email IS 'Email address of the user who took the quiz.';
COMMENT ON COLUMN quiz_results.business_name IS 'Optional business name provided by the user.';
COMMENT ON COLUMN quiz_results.challenge IS 'User''s answer to the "biggest website challenge" question.';
COMMENT ON COLUMN quiz_results.business_type IS 'User''s answer to the "business type" question.';
COMMENT ON COLUMN quiz_results.budget IS 'User''s answer to the "monthly marketing budget" question.';
COMMENT ON COLUMN quiz_results.goal IS 'User''s answer to the "top goal" question.';
COMMENT ON COLUMN quiz_results.submitted_at IS 'Timestamp when the user submitted the quiz.';

-- Create indexes for better query performance
CREATE INDEX IF NOT EXISTS idx_quiz_results_email ON quiz_results(email);
CREATE INDEX IF NOT EXISTS idx_quiz_results_submitted_at ON quiz_results(submitted_at DESC);

